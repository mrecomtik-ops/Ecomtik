import assert from "node:assert/strict";
import fs from "node:fs";
import {validate,duePosts,editorialBrief} from "./engine.mjs";
const config = JSON.parse(fs.readFileSync(new URL("./campaigns.json",import.meta.url),"utf8"));
const content = JSON.parse(fs.readFileSync(new URL("./queue.json",import.meta.url),"utf8"));
